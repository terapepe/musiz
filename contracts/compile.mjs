// Compiles MusizMusic.sol → build/MusizMusic.json and writes the ABI for the frontend.
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { createRequire } from 'module'
const require = createRequire(import.meta.url)
const solc = require('solc')
const here = path.dirname(fileURLToPath(import.meta.url))

const input = {
  language: 'Solidity',
  sources: { 'MusizMusic.sol': { content: fs.readFileSync(path.join(here, 'MusizMusic.sol'), 'utf8') } },
  settings: { optimizer: { enabled: true, runs: 200 }, viaIR: true, evmVersion: 'paris', outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } } },
}
const findImports = (p) => {
  try { return { contents: fs.readFileSync(path.join(here, 'node_modules', p), 'utf8') } } catch { return { error: 'not found: ' + p } }
}
const out = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }))
const errs = (out.errors || []).filter((e) => e.severity === 'error')
if (errs.length) { errs.forEach((e) => console.error(e.formattedMessage)); process.exit(1) }
const c = out.contracts['MusizMusic.sol'].MusizMusic
fs.mkdirSync(path.join(here, 'build'), { recursive: true })
fs.writeFileSync(path.join(here, 'build/MusizMusic.json'), JSON.stringify({ abi: c.abi, bytecode: '0x' + c.evm.bytecode.object }))
fs.writeFileSync(path.join(here, '../src/config/musicAbi.ts'), `// Generated by contracts/compile.mjs — do not edit\nexport const musicAbi = ${JSON.stringify(c.abi, null, 2)} as const\n`)
console.log('compiled MusizMusic, bytecode', c.evm.bytecode.object.length / 2, 'bytes')
